using NineLivesAudio.Helpers;
using NineLivesAudio.Models;

namespace NineLivesAudio.Services;

/// <summary>
/// Code-based localization (no .resw/PRI required) supporting English and
/// Simplified Chinese. Language preference is stored in <see cref="AppSettings.Language"/>
/// ("system" | "en-US" | "zh-CN"). "system" follows the OS UI language.
/// </summary>
public sealed class LocalizationService : ILocalizationService
{
    private readonly ISettingsService _settingsService;
    private string _currentLanguage = "en-US";

    public LocalizationService(ISettingsService settingsService)
    {
        _settingsService = settingsService;
        _currentLanguage = ResolveLanguage(_settingsService.Settings.Language);
        AppLanguage.SetChinese(_currentLanguage == "zh-CN");
    }

    public string CurrentLanguage => _currentLanguage;
    public bool IsChinese => _currentLanguage == "zh-CN";

    public event Action? LanguageChanged;

    public string GetString(string key)
    {
        if (TryGet(_currentLanguage, key, out var value))
            return value!;
        if (TryGet("en-US", key, out value))
            return value!;
        return key;
    }

    public string Format(string key, params object?[] args)
    {
        var template = GetString(key);
        try { return string.Format(template, args); }
        catch { return template; }
    }

    public async Task SetLanguageAsync(string language)
    {
        var resolved = ResolveLanguage(language);
        _currentLanguage = resolved;
        AppLanguage.SetChinese(resolved == "zh-CN");
        _settingsService.Settings.Language = language;
        await _settingsService.SaveSettingsAsync();
        LanguageChanged?.Invoke();
    }

    /// <summary>Re-reads the persisted preference (call after settings load).</summary>
    public void RefreshFromSettings()
    {
        var resolved = ResolveLanguage(_settingsService.Settings.Language);
        if (resolved != _currentLanguage)
        {
            _currentLanguage = resolved;
            AppLanguage.SetChinese(resolved == "zh-CN");
            LanguageChanged?.Invoke();
        }
    }

    private static string ResolveLanguage(string? preference)
    {
        if (string.Equals(preference, "zh-CN", StringComparison.OrdinalIgnoreCase))
            return "zh-CN";
        if (string.Equals(preference, "en-US", StringComparison.OrdinalIgnoreCase))
            return "en-US";
        // "system" or unset: follow OS UI language
        var culture = System.Globalization.CultureInfo.CurrentUICulture.Name;
        return culture.StartsWith("zh", StringComparison.OrdinalIgnoreCase) ? "zh-CN" : "en-US";
    }

    private static bool TryGet(string language, string key, out string? value)
    {
        value = null;
        if (Resources.TryGetValue(language, out var dict) && dict.TryGetValue(key, out var v))
        {
            value = v;
            return true;
        }
        return false;
    }

